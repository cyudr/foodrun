export function translateIngredient(name: string, lang: SupportedLanguage): string {
  if (lang === 'en') return name;
  const clean = name.toLowerCase().trim();
  if (INGREDIENT_TRANSLATIONS[clean] && INGREDIENT_TRANSLATIONS[clean][lang]) {
    return INGREDIENT_TRANSLATIONS[clean][lang];
  }
  // Partial substring match
  for (const [key, mapping] of Object.entries(INGREDIENT_TRANSLATIONS)) {
    if (clean.includes(key) && mapping[lang]) {
      return mapping[lang];
    }
  }
  return name;
}

